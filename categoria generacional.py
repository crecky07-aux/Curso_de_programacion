año = int(input("ingresa tu año de nacimiento: "))

if año >= 1946 and año <= 1964:
    print("Perteneces a la generación boomer (estas viejo hermano)")  
elif año >= 1965 and año <= 1980:
    print("Perteneces a la generación de los que creen que se la saben todas xd")
elif año >= 1981 and año <= 1996:
    print("Perteneces a la generación de los señores")
elif año >= 1997 and año <= 2012:
    print("Perteneces a la generación de los llorones D:")   
else:
    print ("Usted no esta dentro del rango de las generaciones no definidas")